const schemaID = "https://flywheel.local/schemas/planning.schema.json"

var compiled = sync.OnceValues(func() (map[string]*jsonschema.Schema, error) {
	return compile(templates.FS.ReadFile)
})

func compile(load func(string) ([]byte, error)) (map[string]*jsonschema.Schema, error) {
	raw, err := load("planning.schema.json")
	if err != nil {
		return nil, err
	}
	var value any
	if err := json.Unmarshal(raw, &value); err != nil {
		return nil, err
	}
	c := jsonschema.NewCompiler()
	// This fresh compiler registers one unique absolute resource.
	_ = c.AddResource(schemaID, value)
	result := map[string]*jsonschema.Schema{}
	for _, name := range []string{"", "brief", "design", "plan", "review", "approval", "feedback", "request", "activation-ref", "activation"} {
		id := schemaID
		if name != "" {
			id += "#/$defs/" + name
		}
		schema, err := c.Compile(id)
		if err != nil {
			return nil, err
		}
		result[name] = schema
	}
	return result, nil
}

func validateShape(name string, value any) error {
	schemas, err := compiled()
	if err != nil {
		return err
	}
	return schemas[name].Validate(value)
}

// JSONValue is used only with this package's concrete, JSON-safe structs.
func jsonValue(value any) any {
	raw, _ := json.Marshal(value)
	var result any
	_ = json.Unmarshal(raw, &result)
	return result
}

func shape(name string, value any) error { return validateShape(name, jsonValue(value)) }

// DigestBytes hashes exact artifact bytes. Canonical struct/map JSON below is
// deterministic; no timestamp or model verdict is generated by this package.
func DigestBytes(raw []byte) string {
	h := sha256.Sum256(raw)
	return hex.EncodeToString(h[:])
}

func designDigest(d Design) string {
	d.Ref.Digest = ""
	raw, _ := json.Marshal(d)
	return DigestBytes(raw)
}

func planDigest(p ExecutionPlan) string {
	p.Ref.Digest = ""
	raw, _ := json.Marshal(p)
	return DigestBytes(raw)
}

func ValidateBrief(b Brief) error {
	if err := shape("brief", b); err != nil {
		return err
	}
	if (b.Policy == "delegated" || b.ImplementationAuthorized) && b.Authorization == "" {
		return fmt.Errorf("delegation or implementation authorization requires its original source")
	}
	if b.DesignGranularity == "compact" && (b.Mode == "full" || strings.TrimSpace(b.GranularityReason) == "" || len(b.Evidence) == 0) {
		return fmt.Errorf("compact preparation requires evidence, a selection reason, and no explicit Full request")
	}
	return nil
}

func validateDesign(d Design) error {
	if err := shape("design", d); err != nil {
		return err
	}
	if d.Ref.Digest != designDigest(d) {
		return fmt.Errorf("design %d digest does not match its immutable contents", d.Ref.Revision)
	}
	for _, scope := range d.ImplementationScope {
		if path.IsAbs(scope) || path.Clean(scope) != scope || strings.ContainsAny(scope, "\\\x00\r\n") || scope == ".." || strings.HasPrefix(scope, "../") {
			return fmt.Errorf("implementation scope must contain normalized repository-relative paths")
		}
	}
	ids := map[string]bool{}
	for _, m := range d.Milestones {
		if ids[m.ID] {
			return fmt.Errorf("duplicate milestone %s", m.ID)
		}
		ids[m.ID] = true
	}
	for _, r := range d.Requirements {
		if ids[r.ID] || !ids[r.Milestone] {
			return fmt.Errorf("requirement %s is duplicate or maps to an unknown milestone", r.ID)
		}
		ids[r.ID] = true
	}
	for _, d := range d.Decisions {
		if ids[d.ID] {
			return fmt.Errorf("duplicate decision %s", d.ID)
		}
		ids[d.ID] = true
	}
	return nil
}

func SealDesign(d Design) (Design, error) {
	if d.Decisions == nil {
		d.Decisions = []Decision{}
	}
	d.Ref.Digest = designDigest(d)
	return d, validateDesign(d)
}

func validatePlan(p ExecutionPlan) error {
	if err := shape("plan", p); err != nil {
		return err
	}
	if p.Ref.Digest != planDigest(p) {
		return fmt.Errorf("execution plan %d digest does not match its immutable contents", p.Ref.Revision)
	}
	if p.Preparation == "compact-v1" && (p.Scope != "milestone" || len(p.Files) != 2 || p.Files["spec.md"] == "") {
		return fmt.Errorf("compact preparation requires one complete single-packet projection")
	}
	return nil
}

func SealPlan(p ExecutionPlan) (ExecutionPlan, error) {
	p.Ref.Digest = planDigest(p)
	return p, validatePlan(p)
}

func FindDesign(s *State, ref Ref) *Design {
	for i := range s.Designs {
		if s.Designs[i].Ref == ref {
			return &s.Designs[i]
		}
	}
	return nil
}

func FindPlan(s *State, ref Ref) *ExecutionPlan {
	for i := range s.Plans {
		if s.Plans[i].Ref == ref {
			return &s.Plans[i]
		}
	}
	return nil
}

func LatestReview(s *State, kind string, ref Ref) *Review {
	for i := len(s.Reviews) - 1; i >= 0; i-- {
		if r := &s.Reviews[i]; reviewTarget(*r, kind, ref) {
			return r
		}
	}
	return nil
}

// A compact review is one actual independent record, covering both immutable
// artifacts. It is never copied into fictitious design and plan reviews.
func reviewTarget(r Review, kind string, ref Ref) bool {
	if r.Kind == kind && r.Target == ref {
		return true
	}
	if r.Kind != "compact-v1" {
		return false
	}
	return kind == "design" && r.Target == ref || kind == "plan" && r.Plan != nil && *r.Plan == ref
}

func DesignGranularity(s *State, r Request) string {
	scope, _ := CanonicalScope(r.Scope, r.ScopeID)
	if scope == "design" && r.DesignGranularity != "system" && s.Brief.DesignGranularity == "compact" {
		return "compact"
	}
	return "system"
}

var milestoneScopePattern = regexp.MustCompile(`^M-[0-9]{2,}$`)
var packetScopePattern = regexp.MustCompile(`^M[0-9]{2,}-T[0-9]{2,}$`)

// CanonicalScope keeps the Replan command from creating another authority or
// finding bucket for the same underlying design, milestone or packet.
func CanonicalScope(scope, id string) (string, string) {
	if scope == "design" || scope == "replan" && (id == "" || id == "root") {
		return "design", ""
	}
	if scope == "replan" {
		if milestoneScopePattern.MatchString(id) {
			return "milestone", id
		}
		if packetScopePattern.MatchString(id) {
			return "packet", id
		}
	}
	return scope, id
}

func PlanKey(scope, id string) string {
	scope, id = CanonicalScope(scope, id)
	return scope + "/" + id
}

func validateReview(s *State, r Review) error {
	if err := shape("review", r); err != nil {
		return err
	}
	planner, input := "", 0
	if r.Kind == "design" || r.Kind == "compact-v1" {
		d := FindDesign(s, r.Target)
		if d == nil || r.Role != "design-review" || r.Design != nil {
			return fmt.Errorf("design review target or independent role is invalid")
		}
		planner, input = d.PlannerInvocation, d.InputRevision
		if r.Kind == "compact-v1" {
			if r.Plan == nil {
				return fmt.Errorf("compact review requires its exact execution plan")
			}
			p := FindPlan(s, *r.Plan)
			if p == nil || p.Preparation != "compact-v1" || p.Design != r.Target || p.InputRevision != input || p.PlannerInvocation != planner {
				return fmt.Errorf("compact review must cover the design and plan from one preparation")
			}
			if r.Verdict == "pass" && (p.ScopeVerdict != "within-envelope" || r.ScopeVerdict != "within-envelope" || r.DesignVerdict != "valid" || r.CoverageVerdict != "complete") {
				return fmt.Errorf("compact review requires explicit valid design, complete coverage, and within-envelope verdicts")
			}
		} else if r.Plan != nil {
			return fmt.Errorf("ordinary design review cannot claim compact plan coverage")
		}
		if r.Verdict == "pass" {
			for _, decision := range d.Decisions {
				if decision.Kind == "unresolved" {
					return fmt.Errorf("design review cannot pass an unresolved decision")
				}
			}
		}
	} else {
		p := FindPlan(s, r.Target)
		if p == nil || r.Role != "plan-review" || r.Design == nil || *r.Design != p.Design || r.Plan != nil {
			return fmt.Errorf("plan review target or independent role is invalid")
		}
		planner, input = p.PlannerInvocation, p.InputRevision
		if r.Verdict == "pass" && (p.ScopeVerdict != "within-envelope" || r.ScopeVerdict != "within-envelope") {
			return fmt.Errorf("plan review cannot pass an unresolved or material scope change")
		}
	}
	if r.Invocation == planner || r.InputRevision != input {
		return fmt.Errorf("review must have an independent invocation and matching input revision")
	}
	ids := map[string]bool{}
	for _, finding := range r.Findings {
		if ids[finding.ID] || (finding.Status == "resolved" && finding.Resolution == "") {
			return fmt.Errorf("finding identity or resolution evidence is invalid")
		}
		ids[finding.ID] = true
		if r.Verdict == "pass" && (finding.Severity == "blocker" || finding.Severity == "major") && finding.Status != "resolved" {
			return fmt.Errorf("review cannot pass an unresolved blocking finding")
		}
	}
	return nil
}

// ValidateValue checks unknown fields before typed decoding can discard them.
func ValidateValue(value any) error {
	if err := validateShape("", value); err != nil {
		return err
	}
	raw, _ := json.Marshal(value)
	var s State
	// Schema restricts every integer to the exact portable JSON integer range.
	_ = json.Unmarshal(raw, &s)
	return validateContents(&s)
}

func Validate(s *State) error { return ValidateValue(jsonValue(s)) }

func validateContents(s *State) error {
	if err := ValidateBrief(s.Brief); err != nil {
		return err
	}
	if s.InputRevision != len(s.Feedback)+1 {
		return fmt.Errorf("input revision must preserve every applied feedback event")
	}
	for i, d := range s.Designs {
		if err := validateDesign(d); err != nil {
			return err
		}
		if d.Ref.Revision != i+1 || d.InputRevision > s.InputRevision {
			return fmt.Errorf("design history revisions must be sequential and attributable")
		}
	}
	for i, p := range s.Plans {
		if err := validatePlan(p); err != nil {
			return err
		}
		if p.Ref.Revision != i+1 || p.InputRevision > s.InputRevision || FindDesign(s, p.Design) == nil {
			return fmt.Errorf("plan history revisions or root reference are invalid")
		}
	}
	ids := map[string]bool{}
	for i, r := range s.Reviews {
		if err := validateReview(s, r); err != nil {
			return err
		}
		previous := *s
		previous.Reviews = s.Reviews[:i]
		if err := validateFindingClosure(&previous, r); err != nil {
			return err
		}
		if ids[r.ID] {
			return fmt.Errorf("duplicate review identity")
		}
		ids[r.ID] = true
	}
	for _, a := range s.Approvals {
		if err := validateApproval(s, a, false); err != nil {
			return err
		}
		if ids["approval/"+a.RequestID] {
			return fmt.Errorf("duplicate approval request identity")
		}
		ids["approval/"+a.RequestID] = true
	}
	for _, f := range s.Feedback {
		if f.Target != nil && FindDesign(s, *f.Target) == nil || ids["feedback/"+f.RequestID] {
			return fmt.Errorf("feedback target or request identity is invalid")
		}
		ids["feedback/"+f.RequestID] = true
	}
	rounds := 0
	for _, r := range s.Requests {
		if ids["request/"+r.ID] || r.Rounds > r.MaxRounds || r.InputRevision > s.InputRevision {
			return fmt.Errorf("planning request identity or counters are invalid")
		}
		ids["request/"+r.ID] = true
		rounds += r.Rounds
	}
	if rounds != s.Rounds {
		return fmt.Errorf("planning rounds must equal the cumulative request ledger")
	}
	if s.CurrentDesign != nil && FindDesign(s, *s.CurrentDesign) == nil || s.CurrentPlan != nil && FindPlan(s, *s.CurrentPlan) == nil {
		return fmt.Errorf("current planning reference is missing")
	}
	if len(s.Designs) > 0 && (s.CurrentDesign == nil || *s.CurrentDesign != s.Designs[len(s.Designs)-1].Ref) {
		return fmt.Errorf("current design must retain the latest sealed version")
	}
	for key, ref := range s.CurrentPlans {
		p := FindPlan(s, ref)
		if p == nil || key != PlanKey(p.Scope, p.ScopeID) {
			return fmt.Errorf("current plan scope reference is invalid")
		}
	}
	expectedPlans := map[string]Ref{}
	var expectedPlan *Ref
	for i := range s.Plans {
		p := &s.Plans[i]
		if s.CurrentDesign != nil && p.Design == *s.CurrentDesign {
			expectedPlans[PlanKey(p.Scope, p.ScopeID)] = p.Ref
			expectedPlan = &p.Ref
		}
	}
	if !reflect.DeepEqual(s.CurrentPlans, expectedPlans) || !reflect.DeepEqual(s.CurrentPlan, expectedPlan) {
		return fmt.Errorf("current plan scopes must retain their latest sealed versions")
	}
	for _, activation := range []*Activation{s.Active, s.PendingActivation} {
		if activation != nil {
			if err := validateActivation(s, *activation); err != nil {
				return err
			}
		}
	}
	if s.Active != nil && (s.Active.Stage != "active" || s.Active.Head == "") || s.PendingActivation != nil && s.PendingActivation.Stage == "active" {
		return fmt.Errorf("active and pending transaction stages contradict their ownership")
	}
	return nil
}
